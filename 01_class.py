

class Employee:
    
    language="Py" #This is a class attribute
    salary=1200000

hitesh=Employee()
hitesh.name="Hitesh" # This is an instance(object)attribute
print(hitesh.name,hitesh.language,hitesh.salary) 

rohan=Employee()
rohan.name="Radhika Rohan"
print(rohan.name,rohan.salary,rohan.language)


# (Here name is instance(object) attribute) (and salary and language are class attribute )as they directly belong to the class




